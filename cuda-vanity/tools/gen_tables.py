#!/usr/bin/env python3
"""Generates tables.inc: SHA-256/512 constants (derived from primes) + BIP39 English wordlist."""
import hashlib, math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def primes(n):
    out, c = [], 2
    while len(out) < n:
        if all(c % p for p in out if p * p <= c): out.append(c)
        c += 1
    return out

def icbrt(n):
    lo, hi = 0, 1 << ((n.bit_length() // 3) + 2)
    while lo < hi:
        m = (lo + hi + 1) // 2
        if m ** 3 <= n: lo = m
        else: hi = m - 1
    return lo

P = primes(80)
K256 = [icbrt(p << 96) & 0xffffffff for p in P[:64]]
K512 = [icbrt(p << 192) & (2**64 - 1) for p in P]
IV256 = [math.isqrt(p << 64) & 0xffffffff for p in P[:8]]
IV512 = [math.isqrt(p << 128) & (2**64 - 1) for p in P[:8]]
assert K256[0] == 0x428a2f98 and K512[0] == 0x428a2f98d728ae22
assert IV256[0] == 0x6a09e667 and IV512[0] == 0x6a09e667f3bcc908

words = (ROOT / "data/english.txt").read_text().split()
assert len(words) == 2048
assert hashlib.sha256(("\n".join(words) + "\n").encode()).hexdigest() == \
    "2f5eed53a4727b4bf8880d8f3f199efc90e58503646d9ff8eff3a2ed3b24dbda"

def arr(v, w): return "{" + ",".join("0x%0*x%s" % (w // 4, x, "ULL" if w == 64 else "u") for x in v) + "}"
with (ROOT / "build/tables.inc").open("w") as f:
    f.write("// generated by gen_tables.py -- do not edit\n")
    f.write("#define K256_INIT %s\n" % arr(K256, 32))
    f.write("#define K512_INIT %s\n" % arr(K512, 64))
    f.write("#define IV256_INIT %s\n" % arr(IV256, 32))
    f.write("#define IV512_INIT %s\n" % arr(IV512, 64))
    wl = ",".join("{" + ",".join(str(ord(c)) if i < len(w) else "0" for i, c in enumerate((w + "\0" * 8)[:8])) + "}" for w in words)
    f.write("#define WORDLIST_INIT {%s}\n" % wl)
print("tables.inc written")
